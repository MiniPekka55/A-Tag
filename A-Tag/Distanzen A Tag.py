GESCHWINDIGKEIT = 16  # km/h mit dem Fahrrad


def fahrzeit_minuten(von, nach):
    """Fahrzeit in Minuten zwischen zwei Orten."""
    km = Distanzen[von][nach]
    return km / GESCHWINDIGKEIT * 60


def alle_strecken_ausgeben():
    """Gibt jede Strecke zwischen zwei Orten einmal aus."""
    orte = list(Distanzen)
    nummer = 1
    for i in range(len(orte)):
        for j in range(i + 1, len(orte)):   # j > i: jedes Paar nur einmal
            start = orte[i]
            ziel = orte[j]
            km = Distanzen[start][ziel]
            minuten = round(fahrzeit_minuten(start, ziel))
            print(f"{nummer:>3}. {start:<16} -> {ziel:<16} {km:>2} km  {minuten:>2} Min")
            nummer += 1


if input("Liste mit allen Strecken anzeigen? (j/n) ") == "j":
    alle_strecken_ausgeben()

print("\nMögliche Orte:", ", ".join(Distanzen))

while True:
    start = input("\nVon welchem Ort? (Enter = beenden) ").strip().title()
    if start == "":
        break
    ziel = input("Nach welchem Ort? ").strip().title()

    if start not in Distanzen:
        print(f'"{start}" gibt es nicht.')
    elif ziel not in Distanzen:
        print(f'"{ziel}" gibt es nicht.')
    else:
        km = Distanzen[start][ziel]
        minuten = fahrzeit_minuten(start, ziel)
        print(f"Von {start} nach {ziel}: {km} km, ca. {round(minuten)} Minuten mit {GESCHWINDIGKEIT} km/h")