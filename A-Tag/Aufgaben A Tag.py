GESCHWINDIGKEIT = 16  # km/h mit dem Fahrrad


def fahrzeit(von, nach):
    """Fahrzeit in Stunden zwischen zwei Orten."""
    return Distanzen[von][nach] / GESCHWINDIGKEIT


def konzerte_in_ort(ort):
    liste = []
    if ort not in Distanzen:
        print(f'"{ort}" gibt es nicht. Mögliche Orte:', ", ".join(Distanzen))
        return liste

    for band, daten in Konzerte.items():
        if daten["Ort"] == ort:
            for schluessel, zeiten in daten.items():
                if schluessel.startswith("Konzert"):
                    anfang = zeiten[0]
                    ende = zeiten[1]
                    liste.append([anfang, ende, band, ort])
    return liste


def strecke(plan):
    """Gesamte Fahrstrecke eines Plans in km."""
    km = 0
    for i in range(1, len(plan)):
        km += Distanzen[plan[i - 1][3]][plan[i][3]]
    return km


def beste_plaene(plan, moegliche):
    """Probiert alle Möglichkeiten durch und gibt ALLE Pläne mit den meisten Konzerten zurück."""
    beste = [plan]
    for konzert in moegliche:
        anfang, ende, band, ort = konzert
        if len(plan) > 0:
            letzter = plan[-1]
            # Schafft man es rechtzeitig vom letzten Konzert hierher?
            if letzter[1] + fahrzeit(letzter[3], ort) > anfang:
                continue
            # Jede Band nur einmal
            if band in [k[2] for k in plan]:
                continue

        danach = [k for k in moegliche if k[0] >= ende]
        kandidaten = beste_plaene(plan + [konzert], danach)

        if len(kandidaten[0]) > len(beste[0]):
            beste = kandidaten              # neuer Rekord: alte Pläne weg
        elif len(kandidaten[0]) == len(beste[0]):
            beste = beste + kandidaten      # gleich gut: dazunehmen
    return beste

def alle_moeglichkeiten(plan, moegliche, ergebnis):
    """Brute Force: sammelt JEDEN machbaren Plan in ergebnis (auch die leere Menge)."""
    ergebnis.append(plan)
    for konzert in moegliche:
        anfang, ende, band, ort = konzert
        if len(plan) > 0:
            letzter = plan[-1]
            # Schafft man es rechtzeitig vom letzten Konzert hierher?
            if letzter[1] + fahrzeit(letzter[3], ort) > anfang:
                continue
            # Jede Band nur einmal
            if band in [k[2] for k in plan]:
                continue

        danach = [k for k in moegliche if k[0] >= ende]
        alle_moeglichkeiten(plan + [konzert], danach, ergebnis)


def plan_als_text(plan):
    if len(plan) == 0:
        return "(leere Menge)"
    return ", ".join(f"{k[0]} {k[2]} ({k[3]})" for k in plan)

def programm_ausgeben(programm):
    programm.sort()
    print(f"\nDein Programm ({len(programm)} Konzerte):")
    vorheriger_ort = None
    for nummer, (anfang, ende, band, ort) in enumerate(programm, 1):
        if vorheriger_ort is not None and vorheriger_ort != ort:
            km = Distanzen[vorheriger_ort][ort]
            minuten = round(km / GESCHWINDIGKEIT * 60)
            print(f"     -> {km} km Fahrt nach {ort} ({minuten} Min)")
        print(f"  {nummer}. {band}: {anfang} - {ende} Uhr ({ort})")
        vorheriger_ort = ort
    print(f"Gesamt: {strecke(programm)} km")


